def n_buter(func): # Создание функции декоратора, в func будет лежать прикрепляемая функция
    def wrapper(): # Функция обертка в ней вызывается наша функция
        print("Булочка")
        func()
        print("Булочка")

    return wrapper

@n_buter # Вызов декоратора и изменений функции ниже на модифицированную обертку
def ing():
    for elem in ["Горчица","Котлета", "Сыр", "Листья салата", "Лук", "Кетчуп"]:
        print(elem)
ing()